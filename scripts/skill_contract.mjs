#!/usr/bin/env node
/** Generate or verify the source-bound tool contract for `skills/es-browser-agent/contract.md`. */
import { createHash } from 'node:crypto';
import { lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CONTRACT_REL = 'skills/es-browser-agent/contract.md';

function extractUnionLiterals(sourceText, typeName) {
  const re = new RegExp(`export\\s+type\\s+${typeName}\\s*=([\\s\\S]*?);`);
  const match = sourceText.match(re);
  if (!match) throw new Error(`Missing type ${typeName} in source`);
  return Array.from(match[1].matchAll(/'([^']+)'/g), (m) => m[1]);
}

function extractMcpTools(sourceText) {
  const names = Array.from(sourceText.matchAll(/name:\s*'([^']+)'[\s\S]*?description:\s*'([^']+)'/g));
  if (names.length === 0) throw new Error('Unable to parse MCP_TOOLS from stdio-server.ts');
  return names.map((m) => ({ name: m[1], description: m[2] }));
}

function extractCliHelpLines(sourceText) {
  const blockMatch = sourceText.match(/function getHelpText\(\): string \{[\s\S]*?return \[([\s\S]*?)\]\.join\('\\n'\);/);
  if (!blockMatch) throw new Error('Unable to parse CLI help block from dispatch.ts');
  return Array.from(blockMatch[1].matchAll(/^\s*'([^']+)'/gm), (m) => m[1]).filter(
    (line) => line.startsWith('  '),
  );
}

export function renderContract(repoRoot = ROOT) {
  const rpcSrc = readFileSync(resolve(repoRoot, 'shared/rpc-envelope.ts'), 'utf8');
  const schemaSrc = readFileSync(resolve(repoRoot, 'shared/linkedin-schema.ts'), 'utf8');
  const mcpSrc = readFileSync(resolve(repoRoot, 'cli/src/mcp/stdio-server.ts'), 'utf8');
  const cliSrc = readFileSync(resolve(repoRoot, 'cli/src/commands/dispatch.ts'), 'utf8');

  const outcomes = extractUnionLiterals(rpcSrc, 'DispatchOutcome');
  const gates = extractUnionLiterals(rpcSrc, 'HumanGateState');
  const actions = extractUnionLiterals(schemaSrc, 'LinkedInActionName');
  const categories = extractUnionLiterals(schemaSrc, 'LinkedInSearchCategory');
  const draftKinds = extractUnionLiterals(schemaSrc, 'CopilotDraftKind');
  const mcpTools = extractMcpTools(mcpSrc);
  const cliLines = extractCliHelpLines(cliSrc);

  const body = [
    '# Source-Bound Contract (`es-browser-agent`)',
    '',
    '> GENERATED by `scripts/skill_contract.mjs` from `shared/`, `cli/src/`. Do not hand-edit.',
    '',
    '## Transport & Broker Endpoint',
    '',
    '- Host: `127.0.0.1`',
    '- Registered Port: `4347` (`ws://127.0.0.1:4347/ws`, HTTP `POST http://127.0.0.1:4347/rpc`, `GET /health`)',
    '- MV3 Service Worker Keepalive: `20000 ms` WebSocket ping/pong + `0.5 min` backup alarm',
    '- Extension Targets: Chromium MV3 (`extension/dist/chromium`) and Firefox MV3 (`extension/dist/firefox`)',
    '- Debugging Restriction: `debuggerAttached = false` (`chrome.debugger` permission forbidden)',
    '',
    '## CLI Surface (`node cli/dist/browser-agent.js`)',
    '',
    '```text',
    ...cliLines.map((l) => l.trimEnd()),
    '```',
    '',
    '## MCP `stdio` Tools (`node cli/dist/browser-agent.js mcp`)',
    '',
    ...mcpTools.map((t) => `- \`${t.name}\` — ${t.description}`),
    '',
    '## LinkedIn RPC Actions, Categories & Draft Kinds',
    '',
    `- Actions (${actions.length}): ${actions.map((a) => `\`${a}\``).join(', ')}`,
    `- Search categories: ${categories.map((c) => `\`${c}\``).join(', ')}`,
    `- Copilot draft kinds: ${draftKinds.map((k) => `\`${k}\``).join(', ')}`,
    `- Dispatch outcomes: ${outcomes.map((o) => `\`${o}\``).join(', ')}`,
    `- Human Gate states: ${gates.map((g) => `\`${g}\``).join(', ')}`,
    '',
    '## Declarative Run Spec Schema (`examples/*.json`)',
    '',
    'Required top-level JSON keys for `skills/es-browser-agent/build.mjs`:',
    '- `concept`: `"cache-query" | "zero-drift-read" | "copilot-draft" | "new-domain-adapter"`',
    '- `targetUrl`: LinkedIn or loopback fixture URL',
    '- `cacheSql`: non-empty single `SELECT` / `WITH` statement checked prior to live tab access',
    '- `actions`: ordered array of `{ id, action, params, expectOutcome?, expectHumanGate? }`',
    '- `draft`: optional `{ kind, target, body, prefill }` (must always preserve `sent: false`)',
    '',
  ].join('\n');

  const sha256 = createHash('sha256').update(body, 'utf8').digest('hex');
  return Buffer.from(`<!-- contract-sha256: ${sha256} -->\n${body}`, 'utf8');
}

function main() {
  const checkMode = process.argv.includes('--check');
  const expected = renderContract(ROOT);
  const outPath = resolve(ROOT, CONTRACT_REL);

  if (checkMode) {
    try {
      const st = lstatSync(outPath);
      if (st.isSymbolicLink() || !st.isFile()) {
        process.stderr.write('contract: contract.md must be a regular file, not a symlink\n');
        process.exit(1);
      }
      const actual = readFileSync(outPath);
      if (!actual.equals(expected)) {
        process.stderr.write('contract: regenerate contract.md via `node scripts/skill_contract.mjs`\n');
        process.exit(1);
      }
      process.stdout.write('ok: contract\n');
      process.exit(0);
    } catch {
      process.stderr.write('contract: missing contract.md — run `node scripts/skill_contract.mjs`\n');
      process.exit(1);
    }
  }

  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, expected);
  process.stdout.write(`${CONTRACT_REL}\n`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main();
}
